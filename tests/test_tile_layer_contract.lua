local t = require("tests.helpers.test_assert")
local env = require("tests.helpers.test_env")
local mock = require("tests.mock.factorio_runtime")
t.start()

local world, surface = env.create_world()
local position = { x = 0, y = 0 }
surface.set_tiles({ { name = "water", position = position } })
-- Isolate mock engine semantics from mod callbacks in this contract test.
script.on_event({ defines.events.on_player_built_tile, defines.events.on_player_mined_tile }, function() end)
world:build_tiles(surface, { position }, "landfill")
t.eq(surface.get_hidden_tile(position), "water", "landfill preserves wet ground as hidden tile")
world:build_tiles(surface, { position }, "concrete")
t.eq(surface.get_hidden_tile(position), "landfill", "paving preserves foundation as hidden")
t.eq(surface.get_double_hidden_tile(position), "water", "paving over foundation pushes original terrain to double hidden")
world:mine_tiles(surface, { position })
t.eq(surface.get_tile(position).name, "landfill", "mining pavement reveals landfill")
t.eq(surface.get_hidden_tile(position), "water", "original wet terrain remains beneath revealed landfill")
world:mine_tiles(surface, { position })
t.eq(surface.get_tile(position).name, "water", "mining landfill reveals original water")
t.eq(surface.get_hidden_tile(position), nil, "uncovered water has no hidden tile")

surface.set_tiles({ { name = "lake-shallow", position = position } })
world:build_tiles(surface, { position }, "landfill")
t.eq(surface.get_hidden_tile(position), "lake-shallow", "landfill preserves nonmineable dried ground")
surface.set_hidden_tile(position, "lake-dry-water-shallow")
world:mine_tiles(surface, { position })
t.eq(surface.get_tile(position).name, "lake-dry-water-shallow", "script-adjusted hidden dry type survives mining")
world:build_tiles(surface, { position }, "concrete")
world:build_tiles(surface, { position }, "stone-path")
t.eq(surface.get_hidden_tile(position), "lake-dry-water-shallow", "replacing pavement retains original ground")
local events = 0
script.on_event(defines.events.on_player_mined_tile, function(event)
    events = events + 1
    t.eq(event.tiles[1].old_tile.name, "stone-path", "mined event names removed pavement")
    t.eq(surface.get_tile(position).name, "lake-dry-water-shallow", "mined event runs after revealing terrain")
end)
t.eq(world:mine_tiles(surface, { position, { x = 9, y = 9 } }), 1, "only successful tile removals enter event")
t.eq(world:mine_tiles(surface, { position }), 0, "nonmineable ground is not removed")
t.eq(events, 1, "failed removal raises no mined event")
t.finish("Mock tile layers and mined event contract")
assert(not t.has_failures(), "mock tile contract failed")
